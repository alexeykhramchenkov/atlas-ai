

from __future__ import annotations

import os
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

try:
    import psycopg
except ImportError as exc:
    raise SystemExit(
        "Missing dependency: psycopg. Install it with: pip install psycopg[binary]"
    ) from exc


PROJECT_ROOT = Path(__file__).resolve().parents[1]
OUTPUT_PATH = PROJECT_ROOT / "project_docs" / "SUPABASE_SCHEMA.md"

INCLUDED_SCHEMAS = {"public"}

EXCLUDED_TABLE_PREFIXES = ("pg_", "sql_")
ENV_PATH = PROJECT_ROOT / ".env"


COLUMNS_SQL = """
select
    table_schema,
    table_name,
    ordinal_position,
    column_name,
    data_type,
    udt_name,
    is_nullable,
    column_default
from information_schema.columns
where table_schema = any(%s)
order by table_schema, table_name, ordinal_position;
"""

TABLES_SQL = """
select
    table_schema,
    table_name,
    table_type
from information_schema.tables
where table_schema = any(%s)
order by table_schema, table_name;
"""

INDEXES_SQL = """
select
    schemaname as table_schema,
    tablename as table_name,
    indexname,
    indexdef
from pg_indexes
where schemaname = any(%s)
order by schemaname, tablename, indexname;
"""

ROW_COUNTS_SQL = """
select
    schemaname as table_schema,
    relname as table_name,
    n_live_tup::bigint as estimated_rows
from pg_stat_user_tables
where schemaname = any(%s)
order by schemaname, relname;
"""


def main() -> None:
    load_env_file(ENV_PATH)
    database_url = get_database_url()

    with psycopg.connect(database_url) as conn:
        tables = fetch_dicts(conn, TABLES_SQL, [list(INCLUDED_SCHEMAS)])
        columns = fetch_dicts(conn, COLUMNS_SQL, [list(INCLUDED_SCHEMAS)])
        indexes = fetch_dicts(conn, INDEXES_SQL, [list(INCLUDED_SCHEMAS)])
        row_counts = fetch_dicts(conn, ROW_COUNTS_SQL, [list(INCLUDED_SCHEMAS)])

    markdown = build_markdown(
        tables=tables,
        columns=columns,
        indexes=indexes,
        row_counts=row_counts,
    )

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(markdown, encoding="utf-8")

    print(f"Updated: {OUTPUT_PATH}")

def load_env_file(path: Path) -> None:
    if not path.exists():
        return

    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()

        if not line or line.startswith("#") or "=" not in line:
            continue

        key, value = line.split("=", 1)
        key = key.strip()
        value = value.strip().strip('"').strip("'")

        if key and key not in os.environ:
            os.environ[key] = value


def get_database_url() -> str:
    database_url = (
        os.getenv("DATABASE_URL")
        or os.getenv("SUPABASE_DB_URL")
        or os.getenv("POSTGRES_URL")
    )

    if not database_url:
        raise SystemExit(
            "Database URL not found. Set one of: DATABASE_URL, SUPABASE_DB_URL, POSTGRES_URL. You can put it into .env. This must be a Postgres connection string, not SUPABASE_URL."
        )

    return database_url


def fetch_dicts(conn, sql: str, params: list) -> list[dict]:
    with conn.cursor() as cur:
        cur.execute(sql, params)
        columns = [description.name for description in cur.description]
        return [dict(zip(columns, row)) for row in cur.fetchall()]


def build_markdown(
    *,
    tables: list[dict],
    columns: list[dict],
    indexes: list[dict],
    row_counts: list[dict],
) -> str:
    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    columns_by_table = group_by_table(columns)
    indexes_by_table = group_by_table(indexes)
    row_count_by_table = {
        table_key(row): row.get("estimated_rows")
        for row in row_counts
    }

    visible_tables = [
        table for table in tables
        if should_include_table(table["table_name"])
    ]

    lines: list[str] = [
        "# Supabase Schema",
        "",
        f"Generated at: `{generated_at}`",
        "",
        "This file is auto-generated by:",
        "",
        "```bash",
        "python project_docs/update_supabase_schema.py",
        "```",
        "",
        "## Summary",
        "",
        f"Tables/views: `{len(visible_tables)}`",
        "",
        "| Schema | Table | Type | Estimated rows | Columns |",
        "|---|---|---:|---:|---:|",
    ]

    for table in visible_tables:
        key = table_key(table)
        table_columns = columns_by_table.get(key, [])
        estimated_rows = row_count_by_table.get(key, "")
        lines.append(
            f"| `{table['table_schema']}` | `{table['table_name']}` | "
            f"`{table['table_type']}` | `{estimated_rows}` | `{len(table_columns)}` |"
        )

    lines.extend([
        "",
        "## Tables",
        "",
    ])

    for table in visible_tables:
        key = table_key(table)
        table_columns = columns_by_table.get(key, [])
        table_indexes = indexes_by_table.get(key, [])
        estimated_rows = row_count_by_table.get(key, "")

        lines.extend([
            f"### `{table['table_schema']}.{table['table_name']}`",
            "",
            f"Type: `{table['table_type']}`  ",
            f"Estimated rows: `{estimated_rows}`",
            "",
            "#### Columns",
            "",
            "| # | Column | Type | Nullable | Default |",
            "|---:|---|---|---|---|",
        ])

        for column in table_columns:
            data_type = format_data_type(column)
            default = format_default(column.get("column_default"))
            lines.append(
                f"| {column['ordinal_position']} | `{column['column_name']}` | "
                f"`{data_type}` | `{column['is_nullable']}` | {default} |"
            )

        if table_indexes:
            lines.extend([
                "",
                "#### Indexes",
                "",
            ])

            for index in table_indexes:
                lines.extend([
                    f"- `{index['indexname']}`",
                    "",
                    "```sql",
                    index["indexdef"],
                    "```",
                    "",
                ])

        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def group_by_table(rows: list[dict]) -> dict[tuple[str, str], list[dict]]:
    grouped: dict[tuple[str, str], list[dict]] = defaultdict(list)

    for row in rows:
        grouped[table_key(row)].append(row)

    return dict(grouped)


def table_key(row: dict) -> tuple[str, str]:
    return row["table_schema"], row["table_name"]


def should_include_table(table_name: str) -> bool:
    return not table_name.startswith(EXCLUDED_TABLE_PREFIXES)


def format_data_type(column: dict) -> str:
    data_type = column.get("data_type") or ""
    udt_name = column.get("udt_name") or ""

    if data_type == "USER-DEFINED" and udt_name:
        return udt_name

    if data_type == "ARRAY" and udt_name:
        return udt_name

    return data_type


def format_default(value) -> str:
    if value is None:
        return ""

    text = str(value).replace("\n", " ")

    if len(text) > 80:
        text = text[:77] + "..."

    return f"`{text}`"


if __name__ == "__main__":
    main()